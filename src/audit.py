"""Inspect the input CSV and report exact-duplicate and class-balance statistics.

Run from the repository root:
    python -m src.audit

No patient-level identifiers or raw records are exported in the report.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from src.data import DATASET_COLUMNS, normalize_column


def _label_counts(frame: pd.DataFrame) -> dict[str, int]:
    labels = frame["class"].astype("string").str.strip().str.lower()
    return {str(key): int(value) for key, value in sorted(labels.value_counts(dropna=False).items(), key=lambda kv: str(kv[0]))}


def summarize_dataset(csv_path: str | Path) -> dict:
    """Summarize original rows before and after the same deduplication as training."""
    csv_path = Path(csv_path)
    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Dataset not found: {csv_path}. Run `python scripts/download_data.py` first."
        )

    raw = pd.read_csv(csv_path, na_values=["?", "", "NA", "N/A"])
    raw = raw.rename(columns=normalize_column)
    missing_columns = sorted(set(DATASET_COLUMNS) - set(raw.columns))
    if missing_columns:
        raise ValueError(f"The CSV is missing expected columns: {missing_columns}")

    raw = raw[DATASET_COLUMNS]
    unique = raw.drop_duplicates().reset_index(drop=True)
    n_raw = len(raw)
    n_unique = len(unique)
    missing = {col: int(raw[col].isna().sum()) for col in DATASET_COLUMNS}
    return {
        "dataset": "UCI Early Stage Diabetes Risk Prediction (ID 529)",
        "original_rows": n_raw,
        "unique_rows": n_unique,
        "exact_duplicate_rows": n_raw - n_unique,
        "exact_duplicate_fraction": round((n_raw - n_unique) / n_raw, 4) if n_raw else 0.0,
        "predictor_count": len(DATASET_COLUMNS) - 1,
        "raw_class_counts": _label_counts(raw),
        "deduplicated_class_counts": _label_counts(unique),
        "missing_values_by_column": missing,
        "deduplication_rule": "drop exact duplicate rows across all 16 predictors and the target, before splitting",
    }


def render_markdown(result: dict) -> str:
    missing = result["missing_values_by_column"]
    missing_present = {col: count for col, count in missing.items() if count > 0}
    class_rows = [
        f"| {label} | {count} | {result['deduplicated_class_counts'].get(label, 0)} |"
        for label, count in result["raw_class_counts"].items()
    ]
    missing_text = (
        ", ".join(f"`{column}`: {count}" for column, count in missing_present.items())
        if missing_present else "None detected as missing by pandas."
    )
    lines = [
        "# Dataset quality audit", "",
        "> Generated by `python -m src.audit` from the downloaded UCI CSV.", "",
        f"- Original records: **{result['original_rows']}**",
        f"- Unique records after exact-row deduplication: **{result['unique_rows']}**",
        f"- Exact duplicate rows removed: **{result['exact_duplicate_rows']}** "
        f"({100 * result['exact_duplicate_fraction']:.1f}% of original rows)",
        f"- Predictor variables: **{result['predictor_count']}**", "",
        "## Class distribution", "",
        "| Class | Original records | Records after deduplication |",
        "|---|---:|---:|", *class_rows, "",
        "## Missing values", "", missing_text, "",
        "## Interpretation", "",
        "The experiment removes exact duplicate *rows* before the stratified train/test split "
        "to prevent identical records appearing in both partitions. Identical questionnaire answers "
        "may, however, come from different people; without patient identifiers this cannot be checked. "
        "Therefore deduplication is a modeling choice, not a verified patient-level cleaning step.",
        "", "This single-site, symptom-questionnaire dataset is insufficient for clinical deployment or "
        "population-level generalization claims.", "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/raw/diabetes_data_upload.csv"))
    parser.add_argument("--output", type=Path, default=Path("results"))
    args = parser.parse_args()

    result = summarize_dataset(args.data)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "data_audit.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (args.output / "data_audit.md").write_text(
        render_markdown(result), encoding="utf-8"
    )
    print(f"Dataset: {result['original_rows']} original records; {result['unique_rows']} unique records")
    print(f"Exact duplicate rows: {result['exact_duplicate_rows']}")
    print(f"Audit files saved to: {args.output.resolve()}")


if __name__ == "__main__":
    main()
